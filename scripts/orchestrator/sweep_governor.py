class DoerSanitizer:
    """Role: Sanitizer / Cleaner. Safely executes removals and archives from manifest."""

    def __init__(self, root_dir: Optional[Path] = None):
        if root_dir:
            self.root_dir = root_dir
        else:
            vps_dir = Path("/root/video_factory")
            self.root_dir = vps_dir if vps_dir.exists() else Path(__file__).resolve().parent.parent.parent
        self.archive_base = Path("/var/vf/episodes/_archive/sweep_snapshots")
        try:
            self.archive_base.mkdir(parents=True, exist_ok=True)
        except Exception:
            pass

    def execute_remediation(self, manifest: SweepManifest, dry_run: bool = False, force_purge: bool = False) -> ExecutionReport:
        """Executes remediation actions defined in SweepManifest."""
        start_ts = time.time()
        report_id = f"EXEC_{uuid.uuid4().hex[:12].upper()}"
        logger.info(f"=== [DOER SANITIZER] Starting Execution (Report ID: {report_id}, DryRun: {dry_run}) ===")

        items_purged = 0
        items_archived = 0
        items_retained = 0
        bytes_freed = 0
        errors: List[str] = []
        purged_locations: List[str] = []

        for item in manifest.items:
            if item.risk_level == "CRITICAL_PROD_RETAIN":
                items_retained += 1
                continue

            # 1. FILE DELETION
            if item.item_type == "file":
                fpath = Path(item.location)
                if not fpath.exists():
                    continue
                if dry_run:
                    logger.info(f"[DRY-RUN] Would delete file: {fpath} ({item.size_bytes // 1024} KB)")
                    bytes_freed += item.size_bytes
                    items_purged += 1
                    purged_locations.append(str(fpath))
                else:
                    try:
                        fpath.unlink()
                        bytes_freed += item.size_bytes
                        items_purged += 1
                        purged_locations.append(str(fpath))
                        logger.info(f"Purged file: {fpath} ({item.size_bytes // 1024} KB)")
                    except Exception as e:
                        err_msg = f"Failed to delete {fpath}: {e}"
                        logger.error(err_msg)
                        errors.append(err_msg)

            # 2. DIRECTORY PURGE / ARCHIVAL
            elif item.item_type == "directory":
                dpath = Path(item.location)
                if not dpath.exists():
                    continue

                if item.proposed_action == "archive" and not force_purge:
                    if dry_run:
                        logger.info(f"[DRY-RUN] Would archive directory: {dpath}")
                        items_archived += 1
                    else:
                        try:
                            dest = self.archive_base / f"{dpath.name}_{int(time.time())}"
                            shutil.move(str(dpath), str(dest))
                            items_archived += 1
                            logger.info(f"Archived directory {dpath} -> {dest}")
                        except Exception as e:
                            err_msg = f"Failed to archive {dpath}: {e}"
                            logger.error(err_msg)
                            errors.append(err_msg)
                else:
                    if dry_run:
                        logger.info(f"[DRY-RUN] Would purge directory: {dpath} ({item.size_bytes // (1024*1024)} MB)")
                        bytes_freed += item.size_bytes
                        items_purged += 1
                        purged_locations.append(str(dpath))
                    else:
                        try:
                            shutil.rmtree(str(dpath), ignore_errors=True)
                            bytes_freed += item.size_bytes
                            items_purged += 1
                            purged_locations.append(str(dpath))
                            logger.info(f"Purged directory: {dpath}")
                        except Exception as e:
                            err_msg = f"Failed to purge {dpath}: {e}"
                            logger.error(err_msg)
                            errors.append(err_msg)

            # 3. PROCESS TERMINATION
            elif item.item_type == "process":
                pid_str = item.location.replace("pid:", "")
                try:
                    pid = int(pid_str)
                    if dry_run:
                        logger.info(f"[DRY-RUN] Would kill process PID: {pid}")
                        items_purged += 1
                    else:
                        os.kill(pid, signal.SIGKILL)
                        items_purged += 1
                        purged_locations.append(f"PID {pid}")
                        logger.info(f"Terminated process PID: {pid}")
                except ProcessLookupError:
                    pass
                except Exception as e:
                    err_msg = f"Failed to terminate PID {pid_str}: {e}"
                    logger.warning(err_msg)
                    errors.append(err_msg)

            # 4. NOTION ROW ARCHIVAL
            elif item.item_type == "notion_row":
                page_id = item.location.replace("page_id:", "")
                if dry_run:
                    logger.info(f"[DRY-RUN] Would archive Notion page: {page_id}")
                    items_archived += 1
                else:
                    try:
                        sys.path.insert(0, str(self.root_dir))
                        from scripts.ag_notion_bridge import update_page_properties
                        update_page_properties(page_id, {"Status": {"status": {"name": "Archived"}}})
                        items_archived += 1
                        logger.info(f"Archived Notion page: {page_id}")
                    except Exception as e:
                        err_msg = f"Failed to archive Notion page {page_id}: {e}"
                        logger.warning(err_msg)
                        errors.append(err_msg)

            # 5. CLOUDFLARE R2 OBJECT PURGE
            elif item.item_type == "r2_object":
                parts = item.location.replace("r2://", "").split("/", 1)
                if len(parts) == 2:
                    bucket, key = parts[0], parts[1]
                    if dry_run:
                        logger.info(f"[DRY-RUN] Would purge R2 object: {key}")
                        bytes_freed += item.size_bytes
                        items_purged += 1
                    else:
                        try:
                            import boto3
                            s3 = boto3.client(
                                "s3",
                                endpoint_url=os.getenv("R2_ENDPOINT_URL"),
                                aws_access_key_id=os.getenv("R2_ACCESS_KEY_ID"),
                                aws_secret_access_key=os.getenv("R2_SECRET_ACCESS_KEY"),
                                region_name="auto",
                            )
                            s3.delete_object(Bucket=bucket, Key=key)
                            bytes_freed += item.size_bytes
                            items_purged += 1
                            purged_locations.append(f"r2:{key}")
                            logger.info(f"Deleted R2 object: {key}")
                        except Exception as e:
                            err_msg = f"Failed to delete R2 object {key}: {e}"
                            logger.warning(err_msg)
                            errors.append(err_msg)

        dur = round(time.time() - start_ts, 3)
        freed_mb = round(bytes_freed / (1024 * 1024), 2)
        report = ExecutionReport(
            report_id=report_id,
            manifest_id=manifest.manifest_id,
            executed_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
            dry_run=dry_run,
            items_purged=items_purged,
            items_archived=items_archived,
            items_retained=items_retained,
            bytes_freed=bytes_freed,
            freed_mb=freed_mb,
            errors=errors,
            purged_locations=purged_locations,
            duration_seconds=dur,
        )
        logger.info(f"=== [DOER SANITIZER] Remediation Complete: Purged {items_purged} items, Archived {items_archived} items, Freed {freed_mb} MB ===")
        return report


