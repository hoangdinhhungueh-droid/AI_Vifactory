def is_ghost_file(fname: str, parent_path: str) -> bool:
    """Forensic check if a file is a ghost backup or scratch script."""
    if fname in ALLOWLIST_FILES:
        return False
    # Skip public assets and static directories
    if "remotion/public" in parent_path or "assets" in parent_path:
        return False
    # Explicit backup extensions
    if any(fname.endswith(ext) for ext in [".bak", ".backup", ".orig", ".save", ".swp"]):
        return True
    if re.search(r'\.bak(_\d+)?$', fname) or re.search(r'\.backup(_\d+)?$', fname):
        return True
    # Code copies in scripts or app
    if any(fname.endswith(ext) for ext in ["_old.py", "_old.js", "_old.ts", "_old.sh", "_v1.py", "_v1.sh"]):
        return True
    return False


def is_protected_episode(name: str) -> bool:
    """Checks if an episode name matches protected active production episodes."""
    for pattern in PROTECTED_PATTERNS:
        if pattern.lower() in name.lower():
            return True
    return False


@dataclass
class RemnantItem:
    """Individual remnant / ghost item detected during forensic inspection."""
    id: str
    touchpoint: str
    location: str
    item_type: str  # "file", "directory", "process", "notion_row", "r2_object"
    size_bytes: int
    age_hours: float
    risk_level: str  # "SAFE_TO_PURGE", "REQUIRES_ARCHIVE", "CRITICAL_PROD_RETAIN"
    reason: str
    proposed_action: str  # "delete", "archive", "kill", "retain"


@dataclass
class SweepManifest:
    """Structured, immutable contract generated by Lead Detective."""
    manifest_id: str
    created_at: str
    touchpoints_scanned: List[str]
    items: List[RemnantItem] = field(default_factory=list)
    summary: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "manifest_id": self.manifest_id,
            "created_at": self.created_at,
            "touchpoints_scanned": self.touchpoints_scanned,
            "items": [asdict(item) for item in self.items],
            "summary": self.summary,
        }


@dataclass
class ExecutionReport:
    """Report generated by Doer Sanitizer detailing remediation operations."""
    report_id: str
    manifest_id: str
    executed_at: str
    dry_run: bool
    items_purged: int = 0
    items_archived: int = 0
    items_retained: int = 0
    bytes_freed: int = 0
    freed_mb: float = 0.0
    errors: List[str] = field(default_factory=list)
    purged_locations: List[str] = field(default_factory=list)
    duration_seconds: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SweepCertificate:
    """Forensic certificate issued by Lead Verifier certifying system cleanliness."""
    cert_id: str
    issued_at: str
    manifest_id: str
    execution_report_id: str
    zero_remnants_verified: bool
    live_pipeline_ci_status: str
    daemon_health: Dict[str, str]
    sha256_checksum: str
    notes: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


