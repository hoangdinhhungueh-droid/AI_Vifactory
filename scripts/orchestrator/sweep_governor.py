# 🚀 MASTER SWEEP RUNNER
# ==============================================================================

def run_sweep(
    touchpoints: Optional[List[str]] = None,
    dry_run: bool = False,
    force_purge: bool = False,
    run_ci_probe: bool = True,
    output_dir: Optional[Path] = None,
) -> Dict[str, Any]:
    """Coordinates the Lead-Doer-Lead protocol and outputs forensic artifacts."""
    out_dir = output_dir or (Path("/var/vf/logs/sweep") if Path("/var/vf/logs").exists() else Path("logs/sweep"))
    out_dir.mkdir(parents=True, exist_ok=True)

    detective = LeadDetective()
    manifest = detective.generate_manifest(touchpoints=touchpoints)
    
    manifest_file = out_dir / f"{manifest.manifest_id}.json"
    manifest_file.write_text(json.dumps(manifest.to_dict(), indent=2), encoding="utf-8")

    sanitizer = DoerSanitizer()
    report = sanitizer.execute_remediation(manifest, dry_run=dry_run, force_purge=force_purge)

    report_file = out_dir / f"{report.report_id}.json"
    report_file.write_text(json.dumps(report.to_dict(), indent=2), encoding="utf-8")

    verifier = LeadVerifier()
    cert = verifier.verify_sweep(manifest, report, run_ci_probe=run_ci_probe)

    cert_file = out_dir / f"{cert.cert_id}.json"
    cert_file.write_text(json.dumps(cert.to_dict(), indent=2), encoding="utf-8")

    md_file = out_dir / "SWEEP_CERTIFICATE.md"
    md_content = f"""# 🛡️ VF PIPELINE FORENSIC SWEEP CERTIFICATE

- **Certificate ID:** `{cert.cert_id}`
- **Issued At:** `{cert.issued_at}`
- **Manifest ID:** `{cert.manifest_id}`
- **Execution Report ID:** `{cert.execution_report_id}`
- **Cryptographic SHA256:** `{cert.sha256_checksum}`

---

## 📊 Summary of Remediation
- **Mode:** `{'DRY-RUN' if dry_run else 'LIVE PURGE'}`
- **Items Purged:** `{report.items_purged}`
- **Items Archived:** `{report.items_archived}`
- **Items Retained (Protected):** `{report.items_retained}`
- **Storage Freed:** `{report.freed_mb} MB` ({report.bytes_freed} bytes)
- **Zero Remnants Verified:** `{'✅ YES' if cert.zero_remnants_verified else '❌ NO'}`
- **Live Pipeline CI Status:** `{'✅ PASS' if 'PASS' in cert.live_pipeline_ci_status else '❌ FAIL'}`

---

## 🏥 Daemon & Production Service Health
{chr(10).join([f"- **{k}:** `{v}`" for k, v in cert.daemon_health.items()])}

---

## 📝 Forensic Notes
{chr(10).join([f"- {note}" for note in cert.notes])}
"""
    md_file.write_text(md_content, encoding="utf-8")

    return {
        "manifest": manifest.to_dict(),
        "execution_report": report.to_dict(),
        "certificate": cert.to_dict(),
        "certificate_md_path": str(md_file),
    }


