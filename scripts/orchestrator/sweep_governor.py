    def generate_manifest(self, touchpoints: Optional[List[str]] = None) -> SweepManifest:
        """Executes full forensic scan across specified touchpoints and emits SweepManifest."""
        selected_touchpoints = touchpoints or TOUCHPOINTS
        manifest_id = f"MANIFEST_{uuid.uuid4().hex[:12].upper()}"
        logger.info(f"=== [LEAD DETECTIVE] Starting Forensic Scan (Manifest ID: {manifest_id}) ===")

        all_items: List[RemnantItem] = []
        for tp in selected_touchpoints:
            logger.info(f"Inspecting touchpoint: {tp}...")
            if tp == "vps":
                all_items.extend(self.scan_vps())
            elif tp == "notion":
                all_items.extend(self.scan_notion())
            elif tp == "cloudflare_r2":
                all_items.extend(self.scan_cloudflare_r2())
            elif tp == "antigravity_skills":
                all_items.extend(self.scan_antigravity_skills())
            elif tp == "gdrive_youtube":
                all_items.extend(self.scan_gdrive_youtube())

        safe_count = sum(1 for i in all_items if i.risk_level == "SAFE_TO_PURGE")
        archive_count = sum(1 for i in all_items if i.risk_level == "REQUIRES_ARCHIVE")
        retain_count = sum(1 for i in all_items if i.risk_level == "CRITICAL_PROD_RETAIN")
        total_bytes = sum(i.size_bytes for i in all_items)

        summary = {
            "total_items_found": len(all_items),
            "safe_to_purge_count": safe_count,
            "requires_archive_count": archive_count,
            "critical_prod_retain_count": retain_count,
            "total_bytes_candidate": total_bytes,
            "total_mb_candidate": round(total_bytes / (1024 * 1024), 2),
        }

        manifest = SweepManifest(
            manifest_id=manifest_id,
            created_at=datetime.datetime.now(datetime.timezone.utc).isoformat(),
            touchpoints_scanned=selected_touchpoints,
            items=all_items,
            summary=summary,
        )
        logger.info(f"Forensic Scan Complete: {len(all_items)} candidate remnants found ({summary['total_mb_candidate']} MB).")
        return manifest


