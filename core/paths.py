#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""core/paths.py — Single Path Authority for AI Video Factory (AVF-STAB-001).

Implements single source of truth for all paths across the 11 pipeline stages.
Eliminates F2 (Path Entropy). All returned paths are absolute and normalized.
"""

from __future__ import annotations

import logging
import os
import time
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


class RunPaths:
    """Canonical path resolver for a specific Pipeline run or Episode."""

    def __init__(self, run_id: str | Path, repo_root: Optional[Path] = None):
        if isinstance(run_id, Path):
            self.run_id = run_id.name
            self.root = run_id.resolve()
            if repo_root is not None:
                self.repo_root = Path(repo_root).resolve()
            else:
                self.repo_root = self.root.parent
        else:
            clean_id = str(run_id).strip()
            if ".." in clean_id or "/" in clean_id or "\\" in clean_id:
                raise ValueError(f"Path traversal detected in run_id: {run_id!r}")
            self.run_id = clean_id
            if repo_root is not None:
                self.repo_root = Path(repo_root).resolve()
            else:
                # Anchor to workspace root
                self.repo_root = Path(__file__).resolve().parent.parent

            # Support both runs/<run_id> and episodes/<run_id> for backward compatibility.
            # Route all episodes and temporary candidate runs (*_TEMP_*, TEMP_*) to resolve_episodes_dir().
            episodes_base = resolve_episodes_dir(repo_root=self.repo_root, ensure_dir=False)
            if (
                self.run_id.startswith("EP_")
                or "_EP" in self.run_id
                or "_TEMP_" in self.run_id
                or self.run_id.startswith("TEMP_")
                or (episodes_base / self.run_id).exists()
            ):
                self.root = episodes_base / self.run_id
            else:
                self.root = self.repo_root / "runs" / self.run_id

        self.manifest_file = self.root / "run_manifest.json"
        self.log_file = self.root / "pipeline.log"
        self._ensure_dirs()

    def _ensure_dirs(self) -> None:
        """Idempotently creates core directories."""
        self.root.mkdir(parents=True, exist_ok=True)
        self.composite_seeds_dir.mkdir(parents=True, exist_ok=True)
        self.video_clips_dir.mkdir(parents=True, exist_ok=True)
        self.audio_dir.mkdir(parents=True, exist_ok=True)
        self.blocks_dir.mkdir(parents=True, exist_ok=True)

    def ensure_dirs(self) -> None:
        """Idempotently creates core directories (public interface)."""
        self._ensure_dirs()

    @property
    def composite_seeds_dir(self) -> Path:
        """Directory containing final composite seeds ready for I2V."""
        return self.root / "composite_seeds"

    @property
    def video_clips_dir(self) -> Path:
        """Directory containing final raw mp4 video clips generated by Google Flow."""
        return self.root / "video_clips"

    @property
    def audio_dir(self) -> Path:
        """Directory containing voice narration mp3/wav and whisper word timestamps."""
        return self.root / "audio"

    @property
    def blocks_dir(self) -> Path:
        """Directory containing structured sequence block folders."""
        return self.root / "blocks"

    @property
    def final_render_dir(self) -> Path:
        """Directory containing final rendered master video from Remotion."""
        p = self.root / "10_render"
        p.mkdir(parents=True, exist_ok=True)
        return p

    def stage_dir(self, stage_name: str) -> Path:
        """Returns and creates the isolated directory for a given stage."""
        clean_name = str(stage_name).lower().replace(":", "_").replace(" ", "_")
        p = self.root / clean_name
        p.mkdir(parents=True, exist_ok=True)
        return p

    def artifact_file(self, stage_name: str) -> Path:
        """Returns the canonical artifact JSON file path for a stage."""
        return self.stage_dir(stage_name) / "artifact.json"

    def stage_log_file(self, stage_name: str) -> Path:
        """Returns the isolated log file for a stage."""
        return self.stage_dir(stage_name) / "stage.log"

    def seed_image_path(self, scene_id: str) -> Path:
        """Path for a composite seed image."""
        clean_id = str(scene_id).lower()
        return self.composite_seeds_dir / f"composite_{clean_id}.png"

    def video_clip_path(self, scene_id: str) -> Path:
        """Path for a raw video clip."""
        clean_id = str(scene_id).lower()
        return self.video_clips_dir / f"clip_{clean_id}.mp4"


def resolve_run_paths(run_id: str, repo_root: Optional[Path] = None) -> RunPaths:
    """Resolves existing or new RunPaths for a run_id or episode_id."""
    return RunPaths(run_id=run_id, repo_root=repo_root)


def new_run_paths(prefix: str = "RUN", repo_root: Optional[Path] = None) -> RunPaths:
    """Generates a new timestamped RunPaths instance."""
    ts = time.strftime("%Y%m%d_%H%M%S")
    run_id = f"{prefix}_{ts}"
    return RunPaths(run_id=run_id, repo_root=repo_root)


def resolve_state_dir(custom_dir: Optional[str] = None, read_only: bool = False) -> Path:
    """Resolve directory used for lock files and volatile state.
    Single authoritative implementation eliminating split-brain in production.
    """
    if custom_dir:
        p = Path(custom_dir)
        if not read_only:
            p.mkdir(parents=True, exist_ok=True)
        return p

    env_dir = os.getenv("VF_STATE_DIR") or os.getenv("AVF_STATE_DIR") or os.getenv("VF_LOCK_DIR")
    if env_dir:
        p = Path(env_dir)
        if not read_only:
            p.mkdir(parents=True, exist_ok=True)
        return p

    # Standard VPS location
    vps_lock = Path("/var/vf/locks")
    if os.path.isdir("/var/vf") and os.name != "nt":
        try:
            if not read_only:
                vps_lock.mkdir(parents=True, exist_ok=True)
            return vps_lock
        except (PermissionError, OSError) as e:
            logger.error(f"[core.paths] Canonical VPS lock directory /var/vf/locks inaccessible: {e}")
            raise IOError(f"Production lock directory /var/vf/locks unwriteable (fail-closed): {e}") from e

    # Safe repository local fallback (development / test only)
    repo_fallback = Path(__file__).resolve().parent.parent / "var" / "locks"
    if not read_only:
        try:
            repo_fallback.mkdir(parents=True, exist_ok=True)
        except (PermissionError, OSError) as e:
            logger.error(f"[core.paths] Repo lock directory {repo_fallback} unwriteable: {e}")
            raise IOError(f"Local state directory {repo_fallback} unwriteable (fail-closed): {e}") from e
    return repo_fallback


def resolve_topic_history_path(custom_path: Optional[str] = None) -> Path:
    """Canonical resolver for topic_history.json registry (Rule 132/138)."""
    if custom_path:
        return Path(custom_path)
    env_path = os.getenv("TOPIC_HISTORY_PATH") or os.getenv("VF_TOPIC_HISTORY_PATH")
    if env_path:
        return Path(env_path)
    state_dir = os.getenv("VF_STATE_DIR") or os.getenv("AVF_STATE_DIR") or os.getenv("VF_LOCK_DIR")
    if state_dir and ("test" in state_dir.lower() or "PYTEST_CURRENT_TEST" in os.environ):
        return Path(state_dir) / "topic_history.json"
    return Path(__file__).resolve().parent.parent / "data" / "topic_history.json"


def resolve_pending_tasks_dir(ensure_dir: bool = True) -> Path:
    """Canonical resolver for pending tasks directory (Rule 132)."""
    env_dir = os.getenv("PENDING_TASKS_DIR")
    if env_dir:
        p = Path(env_dir)
    elif os.path.isdir("/var/vf/pending_tasks"):
        p = Path("/var/vf/pending_tasks")
    else:
        p = Path(__file__).resolve().parent.parent / "pending_tasks"
    if ensure_dir:
        p.mkdir(parents=True, exist_ok=True)
    return p


def resolve_episodes_dir(
    repo_root: Optional[Path] = None,
    custom_dir: Optional[str] = None,
    ensure_dir: bool = True,
) -> Path:
    """Canonical path resolver for episodes directory (Rule 132).
    Eliminates hardcoded /var/vf/episodes or /root/video_factory paths.
    """
    if custom_dir:
        p = Path(custom_dir)
        if ensure_dir:
            p.mkdir(parents=True, exist_ok=True)
        return p

    env_dir = os.getenv("VF_EPISODES_DIR") or os.getenv("EPISODES_DIR")
    if env_dir:
        p = Path(env_dir)
        if ensure_dir:
            p.mkdir(parents=True, exist_ok=True)
        return p

    if repo_root is not None:
        p = Path(repo_root).resolve() / "episodes"
    else:
        # Canonical VPS production location
        if os.name != "nt" and os.path.isdir("/var/vf/episodes"):
            p = Path("/var/vf/episodes")
        else:
            state_dir = os.getenv("VF_STATE_DIR") or os.getenv("AVF_STATE_DIR")
            if state_dir and (Path(state_dir) / "episodes").is_dir():
                p = Path(state_dir) / "episodes"
            else:
                p = Path(__file__).resolve().parent.parent / "episodes"

    if ensure_dir:
        p.mkdir(parents=True, exist_ok=True)
    return p


def resolve_raw_pool_dir(ensure_dir: bool = True) -> Path:
    """Canonical path resolver for trend discovery RAW_POOL_DIR (Rule 132)."""
    env_dir = os.getenv("VF_RAW_POOL_DIR") or os.getenv("RAW_POOL_DIR")
    if env_dir:
        p = Path(env_dir)
    elif os.name != "nt" and os.path.isdir("/var/vf/db"):
        p = Path("/var/vf/db")
    else:
        repo_root = Path(__file__).resolve().parent.parent
        p = repo_root / "db"
    if ensure_dir:
        p.mkdir(parents=True, exist_ok=True)
    return p


