class TactileContactPoint(BaseModel):
    """Mechanical contact point decided by Opus 5.5."""
    anchor_type: str = Field(..., description="Anchor type: corner_pin, edge_clip, center_stamp, slice_seam, highlight_band, catenary_yarn")
    host_target_area: str = Field(..., description="Target contact zone on host: top_right_corner, left_margin, document_face, paragraph_body, bottom_seal_zone")
    contact_frame_offset: int = Field(default=12, ge=0, le=120, description="Frame trigger for mechanical contact impact (12fps step motion)")
    physical_residue: str = Field(..., description="Residue left behind: red_ink_stain, yellow_glow, paper_tear, needle_hole, embossed_crease")
    snappy_impact_damping: float = Field(default=0.75, ge=0.0, le=1.0, description="Stop-motion damping coefficient (0.0 to 1.0)")


class DynamicMacroCamera(BaseModel):
    """Macro Punch-In camera choreography directed by Opus 5.5."""
    start_scale: float = Field(default=1.0, ge=0.5, le=2.0)
    target_scale: float = Field(default=1.35, ge=1.1, le=1.6, description="Close-up zoom scale into contact target")
    focal_point_norm: List[float] = Field(..., description="Normalized focal point [norm_x, norm_y] between 0.0 and 1.0")
    transition_punch_through: bool = Field(default=True, description="Punch-through zoom to match-cut into next scene")

    @field_validator("focal_point_norm")
    @classmethod
    def validate_focal_point(cls, v: List[float]) -> List[float]:
        if len(v) != 2:
            raise ValueError(f"focal_point_norm must have exactly 2 elements [norm_x, norm_y], got {len(v)}")
        if not (0.0 <= v[0] <= 1.0 and 0.0 <= v[1] <= 1.0):
            raise ValueError(f"focal_point_norm coordinates must be strictly between 0.0 and 1.0, got {v}")
        return v


class DynamicMasterArtManifest(BaseModel):
    """
    Bespoke Master Scene Art Manifest generated by Opus 5.5 / Astra 6 for each scene.
    Enforces Rule 128 (Generic Contracts) and Rule 132 (Decoupled Engine).
    """
    scene_id: str = Field(..., pattern=r"^SCENE_\d{2}$")
    narrative_rationale: str = Field(..., description="Rationale for visual metaphor and prop selection")

    # Image generation prompts
    assembled_keyframe_prompt: str = Field(..., description="AI prompt for generating full assembled 2560x1440 master scene")
    hero_cutout_prompt: str = Field(..., description="AI prompt for generating isolated hero subject on pure #FFFFFF")
    interacting_tool_prompt: str = Field(..., description="AI prompt for generating isolated interacting tool on pure #FFFFFF")

    # Mechanical tactile contact and macro camera directives
    contact_point: TactileContactPoint = Field(..., description="Tactile contact point specification")
    macro_camera: DynamicMacroCamera = Field(..., description="Macro punch-in camera choreography")
    ingress_direction: str = Field(default="right_to_left", description="Direction of fast ingress")
    ingress_duration_sec: float = Field(default=0.3, le=0.4, description="Ingress duration <= 0.4s")
    dual_pass_shadow: bool = Field(default=True, description="Dual-pass contact shadow requirement")


