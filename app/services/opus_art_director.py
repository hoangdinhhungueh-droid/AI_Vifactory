def _clean_json_str(raw: str) -> str:
    """Extracts raw JSON payload from potentially markdown-wrapped LLM text."""
    cleaned = raw.strip()
    if "```json" in cleaned:
        cleaned = cleaned.split("```json", 1)[1].split("```", 1)[0].strip()
    elif "```" in cleaned:
        cleaned = cleaned.split("```", 1)[1].split("```", 1)[0].strip()
    return cleaned


def _generate_contextual_fallback_manifest(
    scene_id: str,
    narration: str,
    headline: str = "",
    context: Optional[Dict[str, Any]] = None,
) -> DynamicMasterArtManifest:
    """
    High-fidelity deterministic fallback if LLM is offline or in dry-run mode.
    Derives unique props, H1-H7 mechanical interactions, and contact points from narration text.
    """
    ctx_obj = context or {}
    extra_text = " ".join(str(ctx_obj.get(k, "")) for k in ["core_idea", "visual_metaphor", "hero_cutout_object", "interacting_tool", "h_family"])
    text_lower = (narration + " " + headline + " " + extra_text).lower()

    # Determine mechanical family and bespoke prop based on narrative keywords
    if any(k in text_lower for k in ["stamp", "sign", "liquidat", "court", "ruling", "official", "formal", "seal"]):
        anchor_type = "center_stamp"
        host_area = "bottom_seal_zone"
        residue = "red_ink_stain"
        tool_desc = "heavy carved wooden handle red ink seal stamp with ornate brass base"
        focal = [0.52, 0.62]
        rationale = "Regulatory / legal enforcement milestone requiring authoritative red stamp impact (H1_IMPACT)."
    elif any(k in text_lower for k in ["highlight", "scrutiny", "audit", "line", "report", "disclose", "read"]):
        anchor_type = "highlight_band"
        host_area = "paragraph_body"
        residue = "yellow_glow"
        tool_desc = "fluorescent yellow chisel-tip forensic highlighter pen resting at dynamic 45 degree angle"
        focal = [0.48, 0.45]
        rationale = "Forensic textual disclosure requiring luminous highlighter pass across critical ledger line (H6_MARK)."
    elif any(k in text_lower for k in ["cut", "sever", "drop", "separat", "split", "bankrupt", "loss", "fell"]):
        anchor_type = "slice_seam"
        host_area = "document_face"
        residue = "paper_tear"
        tool_desc = "vintage stainless steel scalpel blade with knurled grip slicing through paper edge"
        focal = [0.55, 0.40]
        rationale = "Structural bifurcation / fiscal cut represented by physical paper shearing (H3_SEVER)."
    elif any(k in text_lower for k in ["magnify", "zoom", "investigat", "hidden", "detail", "close", "inspect"]):
        anchor_type = "edge_clip"
        host_area = "top_right_corner"
        residue = "embossed_crease"
        tool_desc = "solid antique brass magnifying glass with thick glass lens reflecting archival paper grain"
        focal = [0.58, 0.38]
        rationale = "Detailed forensic scrutiny represented by optical magnification over fine print (H5_OPTICAL)."
    elif any(k in text_lower for k in ["connect", "network", "link", "tie", "flow", "debt", "supply"]):
        anchor_type = "catenary_yarn"
        host_area = "top_right_corner"
        residue = "needle_hole"
        tool_desc = "solid brass bifurcated split pin fastener anchoring twisted organic red thread"
        focal = [0.60, 0.35]
        rationale = "Causal nexus and institutional contagion linked via taut organic evidence yarn (H4_TETHER)."
    else:
        anchor_type = "corner_pin"
        host_area = "left_margin"
        residue = "embossed_crease"
        tool_desc = "black oxide heavy-duty steel wire binder clip gripping the dossier edge"
        focal = [0.42, 0.48]
        rationale = "Institutional documentation clamped and archived for investigative presentation (H2_CONSTRAINT)."

    if ctx_obj.get("interacting_tool"):
        tool_desc = str(ctx_obj["interacting_tool"])

    hero_desc = (
        str(ctx_obj.get("hero_cutout_object"))
        if ctx_obj.get("hero_cutout_object")
        else f"archival evidence document relating to '{headline or 'investigation'}' printed on aged textured cream cardstock with subtle deckle edge"
    )

    full_prompt = (
        f"Authentic Vox tactile paper diorama, scene {scene_id}. Top-down 15-degree rake perspective. "
        f"On aged newsprint kraft paper table (#F4F1EA), a primary {hero_desc} is docked securely. "
        f"A bespoke {tool_desc} actively contacts the host at {host_area}, leaving visible {residue}. "
        "Dual-pass contact shadows with razor-sharp black occlusion edge and soft ambient drop shadow. "
        "Stylized editorial graphic novel lighting, 35mm documentary film grain, clean Swiss composition."
    )

    hero_prompt = (
        f"Isolated subject: {hero_desc}, perfectly centered on pure solid white background #FFFFFF, "
        "crisp clean borders, sharp focus, high contrast, ready for clean alpha channel cutout."
    )

    tool_prompt = (
        f"Isolated prop: {tool_desc}, positioned at dynamic action angle on pure solid white background #FFFFFF, "
        "photographed with sharp defined edges, zero background spill, ready for clean alpha channel cutout."
    )

    return DynamicMasterArtManifest(
        scene_id=scene_id,
        narrative_rationale=rationale,
        assembled_keyframe_prompt=full_prompt,
        hero_cutout_prompt=hero_prompt,
        interacting_tool_prompt=tool_prompt,
        contact_point=TactileContactPoint(
            anchor_type=anchor_type,
            host_target_area=host_area,
            contact_frame_offset=12,
            physical_residue=residue,
            snappy_impact_damping=0.75,
        ),
        macro_camera=DynamicMacroCamera(
            start_scale=1.0,
            target_scale=1.38,
            focal_point_norm=focal,
            transition_punch_through=True,
        ),
        ingress_direction="right_to_left",
        ingress_duration_sec=0.3,
        dual_pass_shadow=True,
    )


def generate_dynamic_art_manifest(
    scene_id: str,
    narration: str,
    headline: str = "",
    context: Optional[Dict[str, Any]] = None,
    preferred_model: str = "claude-opus-5-5",
    fallback_model: str = "gpt-6-astra",
    dry_run: bool = False,
) -> DynamicMasterArtManifest:
    """
    Generates a bespoke DynamicMasterArtManifest for a scene.
    Calls Claude Opus 5.5 via HHTech API (with Astra 6 fallback).
    Enforces Rule 132: Prompt logic is loaded dynamically from config/prompts/cl3_vox_engine/opus_art_director.md.
    """
    if not re.match(r"^SCENE_\d{2}$", scene_id):
        # Normalize scene_01 -> SCENE_01
        m = re.search(r"\d+", scene_id)
        if m:
            scene_id = f"SCENE_{int(m.group(0)):02d}"
        else:
            scene_id = "SCENE_01"

    # Fast offline / test / dry-run path when no HHTech credentials are configured
    from app.services.hhtech_reasoner import get_hhtech_key
    if dry_run or not get_hhtech_key() or os.getenv("VF_TEST_MODE") == "1":
        logger.info(f"[opus_art_director] Using contextual manifest for {scene_id} (offline / test / dry-run).")
        return _generate_contextual_fallback_manifest(
            scene_id=scene_id,
            narration=narration,
            headline=headline,
            context=context,
        )

    system_prompt = get_opus_art_director_rules()
    if not system_prompt:
        logger.warning("[opus_art_director] Missing system prompt from skill_loader, using internal baseline.")
        system_prompt = (
            "You are Claude Opus 5.5, Executive Art Director for Vox-style tactile paper documentaries. "
            "Respond ONLY with valid JSON matching DynamicMasterArtManifest schema."
        )

    user_payload = {
        "scene_id": scene_id,
        "headline": headline,
        "narration": narration,
        "context": context or {},
    }

    prompt_str = (
        f"Direct the bespoke tactile paper collage diorama for this scene.\n\n"
        f"Input Data:\n{json.dumps(user_payload, indent=2, ensure_ascii=False)}\n\n"
        "Requirements:\n"
        "1. Dynamic 100%: Do not use generic props; pick bespoke tools specific to the narration.\n"
        "2. Provide assembled_keyframe_prompt, hero_cutout_prompt (#FFFFFF), and interacting_tool_prompt (#FFFFFF).\n"
        "3. Specify tactile contact point (H1-H7 family, anchor_type, target area, residue).\n"
        "4. Specify macro punch-in camera choreography [norm_x, norm_y].\n"
        "5. Output JSON ONLY conforming to DynamicMasterArtManifest schema."
    )

    gateway = get_global_gateway()

    # 1. Attempt Primary: Claude Opus 5.5
    for model_name in [preferred_model, fallback_model]:
        try:
            logger.info(f"[opus_art_director] Calling {model_name} for {scene_id}...")
            raw_response = gateway.call_llm(
                prompt=prompt_str,
                model=model_name,
                system_prompt=system_prompt,
                temperature=0.25,
                max_tokens=1800,
            )
            cleaned_json = _clean_json_str(raw_response)
            data = json.loads(cleaned_json)

            # Ensure scene_id parity
            data["scene_id"] = scene_id
            manifest = DynamicMasterArtManifest.model_validate(data)
            logger.info(f"[opus_art_director] Successfully generated manifest for {scene_id} via {model_name}.")
            return manifest
        except Exception as err:
            logger.warning(f"[opus_art_director] Attempt with {model_name} for {scene_id} failed: {err}")

    # Fallback to deterministic contextual manifest
    logger.info(f"[opus_art_director] Falling back to contextual programmatic manifest for {scene_id}.")
    return _generate_contextual_fallback_manifest(
        scene_id=scene_id,
        narration=narration,
        headline=headline,
        context=context,
    )
