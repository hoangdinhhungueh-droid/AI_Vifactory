"""
AdaptiveConfig: Strategy DNA & Dynamic Parameter Adaptation Store
=================================================================
Stores and dynamically loads self-evolving rules, symbol overrides,
macro market filters, and LLM Gatekeeper anti-patterns generated by Dreaming.
"""

