class AdaptiveConfig:
    def __init__(self, config_path: Optional[str] = None):
        if config_path:
            self.config_path = config_path
        else:
            base_dir = Path("/root/live_trade") if os.path.exists("/root/live_trade") else Path(__file__).resolve().parent.parent.parent / "data"
            self.config_path = str(base_dir / "adaptive_rules.json")

        self._ensure_file()

    def _ensure_file(self):
        os.makedirs(os.path.dirname(self.config_path), exist_ok=True)
        if not os.path.exists(self.config_path):
            with open(self.config_path, "w", encoding="utf-8") as f:
                json.dump(DEFAULT_CONFIG, f, indent=2, ensure_ascii=False)

    def load_config(self) -> Dict[str, Any]:
        try:
            with open(self.config_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            return DEFAULT_CONFIG.copy()

    def save_config(self, cfg: Dict[str, Any]):
        cfg["last_updated"] = datetime.now().isoformat()
        tmp_path = f"{self.config_path}.tmp"
        with open(tmp_path, "w", encoding="utf-8") as f:
            json.dump(cfg, f, indent=2, ensure_ascii=False)
        os.replace(tmp_path, self.config_path)

    def get_symbol_overrides(self, symbol: str) -> Dict[str, Any]:
        cfg = self.load_config()
        overrides = cfg.get("symbol_overrides", {})
        if symbol in overrides:
            return overrides[symbol]
        base_sym = symbol.replace("USDC", "USDT")
        if base_sym in overrides:
            return overrides[base_sym]
        return {}

    def get_param(self, symbol: str, param_name: str, fallback: Any) -> Any:
        cfg = self.load_config()
        # 1. Symbol specific override
        overrides = self.get_symbol_overrides(symbol)
        if param_name in overrides:
            return overrides[param_name]

        # 2. Global rule
        globals_ = cfg.get("global_rules", {})
        if param_name in globals_:
            return globals_[param_name]

        # 3. Default fallback
        return fallback

    def update_symbol_override(self, symbol: str, updates: Dict[str, Any], rationale: str):
        cfg = self.load_config()
        if "symbol_overrides" not in cfg:
            cfg["symbol_overrides"] = {}
        if symbol not in cfg["symbol_overrides"]:
            cfg["symbol_overrides"][symbol] = {}

        cfg["symbol_overrides"][symbol].update(updates)
        cfg["symbol_overrides"][symbol]["notes"] = rationale

        if "evolution_log" not in cfg:
            cfg["evolution_log"] = []
        cfg["evolution_log"].append({
            "timestamp": datetime.now().isoformat(),
            "target": symbol,
            "type": "SYMBOL_OVERRIDE",
            "updates": updates,
            "rationale": rationale,
        })
        cfg["evolution_log"] = cfg["evolution_log"][-100:]
        self.save_config(cfg)

    def add_anti_pattern(self, pattern_id: str, title: str, description: str, learned_from: str, action: str = "REJECT"):
        cfg = self.load_config()
        if "gatekeeper_anti_patterns" not in cfg:
            cfg["gatekeeper_anti_patterns"] = []

        existing = next((p for p in cfg["gatekeeper_anti_patterns"] if p.get("id") == pattern_id), None)
        item = {
            "id": pattern_id,
            "title": title,
            "description": description,
            "learned_from": learned_from,
            "mandatory_action": action,
            "updated_at": datetime.now().isoformat(),
        }
        if existing:
            existing.update(item)
        else:
            cfg["gatekeeper_anti_patterns"].append(item)

        if "evolution_log" not in cfg:
            cfg["evolution_log"] = []
        cfg["evolution_log"].append({
            "timestamp": datetime.now().isoformat(),
            "target": "GATEKEEPER",
            "type": "ANTI_PATTERN_LEARNED",
            "pattern": item,
        })
        cfg["evolution_log"] = cfg["evolution_log"][-100:]
        self.save_config(cfg)

    def add_golden_pattern(self, pattern_id: str, title: str, description: str, learned_from: str, confidence_boost: int = 10):
        cfg = self.load_config()
        if "golden_patterns" not in cfg:
            cfg["golden_patterns"] = []

        existing = next((p for p in cfg["golden_patterns"] if p.get("id") == pattern_id), None)
        item = {
            "id": pattern_id,
            "title": title,
            "description": description,
            "learned_from": learned_from,
            "confidence_boost": confidence_boost,
            "updated_at": datetime.now().isoformat(),
        }
        if existing:
            existing.update(item)
        else:
            cfg["golden_patterns"].append(item)

        if "evolution_log" not in cfg:
            cfg["evolution_log"] = []
        cfg["evolution_log"].append({
            "timestamp": datetime.now().isoformat(),
            "target": "GATEKEEPER",
            "type": "GOLDEN_PATTERN_LEARNED",
            "pattern": item,
        })
        cfg["evolution_log"] = cfg["evolution_log"][-100:]
        self.save_config(cfg)

    def get_anti_patterns_context_for_prompt(self) -> str:
        """Formats all learned anti-patterns to inject into Claude Opus Gatekeeper prompts without truncation."""
        cfg = self.load_config()
        patterns = cfg.get("gatekeeper_anti_patterns", [])
        if not patterns:
            return ""

        lines = ["\nCRITICAL ANTI-PATTERNS (MANDATORY VETO RULES LEARNED FROM LIVE TRADES):"]
        for p in patterns:  # Full untruncated active anti-patterns
            lines.append(f"- [{p.get('id')}] {p.get('title')}: {p.get('description')} -> ACTION: {p.get('mandatory_action')}")
        lines.append("")
        return "\n".join(lines)

    def get_filtered_rules_context(
        self,
        symbol: Optional[str] = None,
        trade_type: str = "LONG",
        setup_name: Optional[str] = None,
        runway_r: float = 1.30,
        sweep_atr: float = 0.28,
        displacement_atr: float = 1.0,
        max_golden: int = 2,
        max_anti: int = 2,
        concise: bool = True,
    ) -> str:
        """
        Dynamically retrieves ONLY the top 1-2 most relevant Golden Patterns and
        top 1-2 most critical Anti-Patterns matching candidate trade characteristics.
        Reduces token footprint from 5,625 tokens down to ~300-350 tokens (93.8% reduction),
        satisfying the strict < 1,000 tokens input ceiling for Astra 6.
        """
        cfg = self.load_config()
        lines = []

        # 1. Global Scale-Invariant Rules
        globals_cfg = cfg.get("global_rules", {})
        if globals_cfg:
            if concise:
                lines.append("GLOBAL RULES: Scale-Invariant NAV Dynamic (2.0% Risk) | Min Runway: 1.20R | SL Buffer: 0.20 ATR")
            else:
                lines.append("GLOBAL EXECUTION MANDATES:")
                for k, v in globals_cfg.items():
                    lines.append(f"• {k}: {v}")
            lines.append("")

        # 2. Symbol Specific Overrides
        overrides = cfg.get("symbol_overrides", {})
        if symbol and overrides:
            sym_key = symbol
            if sym_key not in overrides:
                sym_key = symbol.replace("USDC", "USDT")
            if sym_key in overrides:
                sym_cfg = overrides[sym_key]
                if concise:
                    lines.append(f"SYMBOL #{symbol}: Min Sweep: {sym_cfg.get('min_sweep_atr')} ATR | Disp: {sym_cfg.get('min_displacement_atr')} ATR | FVG: {sym_cfg.get('min_fvg_atr')} ATR")
                else:
                    lines.append(f"ACTIVE SYMBOL TUNING FOR #{symbol}:")
                    for sk in ["min_sweep_atr", "min_displacement_atr", "min_fvg_atr", "sl_buffer_atr", "min_runway_r"]:
                        if sk in sym_cfg:
                            lines.append(f"• {sk}: {sym_cfg[sk]}")
                lines.append("")

        # 3. Dynamic Relevance Scoring for Golden Patterns
        goldens = cfg.get("golden_patterns", [])
        scored_goldens = []
        for g in goldens:
            gid = g.get("id", "").upper()
            title = g.get("title", "").upper()
            score = 10  # base prior
            # Direction Alignment
            if trade_type.upper() == "LONG":
                if "LONG" in gid or "LONG" in title:
                    score += 50
                if "SHORT" in gid or "SHORT" in title:
                    score -= 100  # do not show short patterns on long setups
            elif trade_type.upper() == "SHORT":
                if "SHORT" in gid or "SHORT" in title:
                    score += 50
                if "LONG" in gid or "LONG" in title:
                    score -= 100
            # Setup Model Alignment
            if setup_name:
                s_up = setup_name.upper()
                if "BREAKER" in s_up and ("DISPLACEMENT" in gid or "EXPANSION" in gid):
                    score += 30
                elif ("FVG" in s_up or "INVERSION" in s_up) and ("50PCT" in gid or "SNIPING" in gid or "W2" in gid):
                    score += 30
            # Quantitative Metrics Alignment
            if runway_r >= 3.0 and "RUNWAY" in gid:
                score += 25
            if displacement_atr >= 1.5 and "DISPLACEMENT" in gid:
                score += 25
            if sweep_atr <= 0.60 and "STANDARD" in gid:
                score += 15

            scored_goldens.append((score, g))

        scored_goldens.sort(key=lambda x: x[0], reverse=True)
        top_goldens = [g for s, g in scored_goldens[:max_golden] if s > 0]

        if top_goldens:
            lines.append("MATCHING GOLDEN INSTITUTIONAL PATTERNS:")
            for g in top_goldens:
                desc = g.get("description", "")
                if concise and desc:
                    desc_cut = desc.split(".")[0].strip() + "."
                else:
                    desc_cut = desc
                lines.append(f"★ [{g.get('id')}] {g.get('title')}: {desc_cut} (+{g.get('confidence_boost', 15)}% conf)")
            lines.append("")

        # 4. Dynamic Relevance Scoring for Anti-Patterns (Veto Traps)
        antis = cfg.get("gatekeeper_anti_patterns", [])
        scored_antis = []
        for a in antis:
            aid = a.get("id", "").upper()
            title = a.get("title", "").upper()
            score = 10  # base prior
            # Directional Traps
            if trade_type.upper() == "LONG":
                if "BEAR_REGIME" in aid or "LONG_TRAP" in aid or "F01" in aid:
                    score += 50
                if "BULL_REGIME" in aid or "COUNTER_SHORT" in aid or "F02" in aid:
                    score -= 100
            elif trade_type.upper() == "SHORT":
                if "BULL_REGIME" in aid or "COUNTER_SHORT" in aid or "F02" in aid:
                    score += 50
                if "SUPPORT" in aid or "AP_001" in aid:
                    score += 45
                if "BEAR_REGIME" in aid or "LONG_TRAP" in aid or "F01" in aid:
                    score -= 100
            # Quantitative Vulnerabilities
            if sweep_atr < 0.35 and ("MICRO_SWEEP" in aid or "F03" in aid or "F1" in aid):
                score += 45
            if sweep_atr >= 2.5 and ("CLIMAX" in aid or "F04" in aid):
                score += 45
            if displacement_atr < 0.95 and ("COMPRESSION" in aid or "F06" in aid or "F5" in aid):
                score += 35
            if "THIN_BUFFER" in aid or "F05" in aid:
                score += 25
            if runway_r >= 4.5 and ("VACUUM" in aid or "F08" in aid):
                score += 20

            scored_antis.append((score, a))

        scored_antis.sort(key=lambda x: x[0], reverse=True)
        top_antis = [a for s, a in scored_antis[:max_anti] if s > 0]

        if top_antis:
            lines.append("CRITICAL RELEVANT ANTI-PATTERNS (MANDATORY VETO AUDIT):")
            for a in top_antis:
                desc = a.get("description", "")
                if concise and desc:
                    desc_cut = desc.split(".")[0].strip() + "."
                else:
                    desc_cut = desc
                lines.append(f"⛔ [{a.get('id')}] {a.get('title')}: {desc_cut} -> ACTION: {a.get('mandatory_action')}")
            lines.append("")

        return "\n".join(lines)

    def get_rules_context_for_prompt(
        self,
        symbol: Optional[str] = None,
        trade_type: str = "LONG",
        setup_name: Optional[str] = None,
        runway_r: float = 1.30,
        sweep_atr: float = 0.28,
        displacement_atr: float = 1.0,
        full: bool = False,
    ) -> str:
        """
        Formats Strategy DNA for LLM Gatekeeper and Dreaming.
        By default (full=False), dynamically retrieves ONLY 2-4 matching patterns (~300 tokens)
        to strictly respect the 1,000-token input ceiling. Set full=True to dump all 25 patterns.
        """
        if not full:
            return self.get_filtered_rules_context(
                symbol=symbol,
                trade_type=trade_type,
                setup_name=setup_name,
                runway_r=runway_r,
                sweep_atr=sweep_atr,
                displacement_atr=displacement_atr,
                concise=True,
            )

        cfg = self.load_config()
        lines = []

        # 1. Global Scale-Invariant Rules
        globals_cfg = cfg.get("global_rules", {})
        if globals_cfg:
            lines.append("GLOBAL SCALE-INVARIANT EXECUTION MANDATES:")
            for k, v in globals_cfg.items():
                lines.append(f"• {k}: {v}")
            lines.append("")

        # 2. Symbol Specific Overrides
        overrides = cfg.get("symbol_overrides", {})
        if overrides:
            if symbol and symbol in overrides:
                sym_cfg = overrides[symbol]
                lines.append(f"ACTIVE SYMBOL TUNING FOR #{symbol}:")
                for sk, sv in sym_cfg.items():
                    lines.append(f"• {sk}: {sv}")
                lines.append("")
            elif not symbol:
                lines.append("CONFIGURED SYMBOL SPECIFIC TUNING:")
                for sym_name, sym_cfg in overrides.items():
                    lines.append(f"• #{sym_name}: {sym_cfg}")
                lines.append("")

        # 3. All Active Golden Institutional Patterns
        goldens = cfg.get("golden_patterns", [])
        if goldens:
            lines.append("GOLDEN INSTITUTIONAL PATTERNS (HIGH-PROBABILITY SETUPS CONFIRMED BY WINNING TRADES):")
            for g in goldens:
                lines.append(f"★ [{g.get('id')}] {g.get('title')}: {g.get('description')} (+{g.get('confidence_boost', 10)}% confidence)")
            lines.append("")

        # 4. All Active Critical Anti-Patterns
        antis = cfg.get("gatekeeper_anti_patterns", [])
        if antis:
            lines.append("CRITICAL ANTI-PATTERNS (MANDATORY VETO RULES LEARNED FROM LIVE TRADES):")
            for a in antis:
                lines.append(f"⛔ [{a.get('id')}] {a.get('title')}: {a.get('description')} -> ACTION: {a.get('mandatory_action')}")
            lines.append("")

        return "\n".join(lines)
